-- ปัญหา: ของที่แกะไปรวมกับรายการอื่น (Greek 500g → Greek 1kg) เดิมลงช่อง used ของต้นทาง
-- ทำให้ดูเหมือน "ขายออก" ทั้งที่ไม่ได้ขาย · ฝั่งปลายทางลง in ทำให้ดูเหมือนของมาจากรถส่ง
-- ผลคือดูตัวเลขแล้วแยกไม่ออกว่าอันไหนขายจริง อันไหนแค่ย้ายกอง — เอาไปวิเคราะห์เมนูไม่ได้
--
-- แก้: ย้ายไปคอลัมน์ของตัวเอง used/in จึงเหลือแต่ของจริง
--   transfer_out  = จำนวน (แพ็ค) ที่ถูกแกะออกไปรวมกับรายการอื่น — ฝั่งต้นทาง
--   transfer_in_g = กรัมที่ได้รับเข้ามาจากการแกะ — ฝั่งปลายทาง (เก็บเป็นกรัม เพราะ 500g ไม่เต็มแพ็ค)
--
-- 2 คอลัมน์นี้ระบบเขียนเองล้วน ๆ พนักงานไม่มีช่องกรอก → เขียนทับได้ตรง ๆ ไม่ต้องมีคอลัมน์
-- ติดตามแยกแบบ expiry_used/expiry_returned (ซึ่งต้องมี เพราะไปปนกับยอดที่พนักงานกรอกเอง)
alter table stock_daily add column if not exists transfer_out  numeric not null default 0;
alter table stock_daily add column if not exists transfer_in_g numeric not null default 0;

-- expiry_in_g ถูกแทนที่ด้วย transfer_in_g — ตอนย้ายยังไม่มีข้อมูลจริงสักแถว (ตรวจแล้ว 0 rows)
alter table stock_daily drop column if exists expiry_in_g;
