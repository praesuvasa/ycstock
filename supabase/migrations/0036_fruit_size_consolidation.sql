-- รวมไซซ์ผลไม้ให้เหลือ "ตัวหลัก" ตัวเดียวต่อกลุ่ม (แพรยืนยัน 2026-07-26)
--   Blueberry  → ตัวหลัก 300g (it-046) · ซ่อน 125g (it-045) และ 500g (it-047)
--   Strawberry → ตัวหลัก 250g (it-043) · ซ่อน 500g (it-044)
--
-- วิธีซ่อน = ตั้ง par เป็น null ("ไม่ stock ในสาขานี้") ไม่ใช่ 0 ("stock แต่ตั้งเป้า 0")
-- เพราะหน้าสต็อก/หน้าเติมของ ใช้ par != null เป็นเงื่อนไขว่าจะโชว์รายการหรือไม่
-- เศษกรัมของทั้งกลุ่มจะไปกองที่ตัวหลักเอง เพราะ leader = สมาชิกที่ par != null ตัวแรก (เรียงตาม sort)
--
-- show_remainder = true ให้ตัวหลัก เพื่อให้หน้าเติมของโชว์ "คงเหลือ 3 +150g" ต่อท้าย (ข้อ 9)

update par_levels set level = null
where item_id in ('it-045', 'it-047', 'it-044');

update items set show_remainder = true
where id in ('it-046', 'it-043');
